CREATE OR REPLACE VIEW
    COVID_ANALYTICS.STAGING.CANONICAL_COUNTRY_CODE_MAP
AS
SELECT
    UPPER(TRIM(indicators.CANONICAL_ISO2)) AS COUNTRY_ISO2,
    UPPER(TRIM(indicators.CANONICAL_ISO3)) AS COUNTRY_ISO3,
    MIN(TRIM(indicators.COUNTRY_NAME)) AS COUNTRY_NAME
FROM COVID_ANALYTICS.RAW.WORLD_BANK_COUNTRY_INDICATORS AS indicators
INNER JOIN COVID_ANALYTICS.RAW.WORLD_BANK_INDICATOR_SNAPSHOTS AS snapshots
    ON indicators.SNAPSHOT_ID = snapshots.SNAPSHOT_ID
WHERE snapshots.IS_ACTIVE
  AND snapshots.PUBLICATION_STATUS = 'ACTIVE'
  AND NULLIF(TRIM(indicators.CANONICAL_ISO2), '') IS NOT NULL
  AND NULLIF(TRIM(indicators.CANONICAL_ISO3), '') IS NOT NULL
  AND NOT indicators.IS_AGGREGATE
GROUP BY
    UPPER(TRIM(indicators.CANONICAL_ISO2)),
    UPPER(TRIM(indicators.CANONICAL_ISO3));

CREATE OR REPLACE TRANSIENT TABLE
    COVID_ANALYTICS.STAGING.JHU_COUNTRY_CUMULATIVE
AS
WITH IDENTIFIED_SOURCE AS (
    SELECT
        TRIM(source.COUNTRY_REGION) AS SOURCE_COUNTRY_NAME,
        NULLIF(UPPER(TRIM(source.ISO3166_1)), '') AS SOURCE_ISO2,
        COALESCE(
            policy.CANONICAL_ISO2,
            source_map.COUNTRY_ISO2
        ) AS CANONICAL_ISO2,
        COALESCE(
            policy.CANONICAL_ISO3,
            source_map.COUNTRY_ISO3
        ) AS CANONICAL_ISO3,
        COALESCE(
            policy_map.COUNTRY_NAME,
            source_map.COUNTRY_NAME,
            policy.SOURCE_COUNTRY_NAME,
            REPLACE(TRIM(source.COUNTRY_REGION), '_', ' ')
        ) AS COUNTRY_NAME,
        source.DATE::DATE AS REPORT_DATE,
        LOWER(TRIM(source.CASE_TYPE)) AS CASE_TYPE,
        source.CASES,
        source.PROVINCE_STATE,
        source.COUNTY,
        COALESCE(policy.SELECTED_LOCATION_LEVEL, 'COUNTRY')
            AS SELECTED_LOCATION_LEVEL,
        COALESCE(
            policy.MAPPING_STATUS,
            IFF(source_map.COUNTRY_ISO3 IS NULL, 'UNMAPPED', 'MAPPED')
        ) AS MAPPING_STATUS,
        COALESCE(
            policy.IS_INCLUDED,
            source_map.COUNTRY_ISO3 IS NOT NULL
        ) AS IS_INCLUDED
    FROM COVID19_EPIDEMIOLOGICAL_DATA.PUBLIC.JHU_COVID_19_TIMESERIES AS source
    LEFT JOIN COVID_ANALYTICS.RAW.JHU_GEOGRAPHY_POLICY AS policy
        ON UPPER(TRIM(source.COUNTRY_REGION))
            = UPPER(policy.SOURCE_COUNTRY_NAME)
       AND EQUAL_NULL(
            NULLIF(UPPER(TRIM(source.ISO3166_1)), ''),
            policy.SOURCE_ISO2
       )
    LEFT JOIN COVID_ANALYTICS.STAGING.CANONICAL_COUNTRY_CODE_MAP AS source_map
        ON NULLIF(UPPER(TRIM(source.ISO3166_1)), '')
            = source_map.COUNTRY_ISO2
    LEFT JOIN COVID_ANALYTICS.STAGING.CANONICAL_COUNTRY_CODE_MAP AS policy_map
        ON policy.CANONICAL_ISO2 = policy_map.COUNTRY_ISO2
    WHERE source.COUNTRY_REGION IS NOT NULL
      AND source.DATE IS NOT NULL
      AND LOWER(TRIM(source.CASE_TYPE)) IN ('confirmed', 'deaths')
),
SELECTED_GEOGRAPHY AS (
    SELECT *
    FROM IDENTIFIED_SOURCE
    WHERE IS_INCLUDED
      AND CANONICAL_ISO3 IS NOT NULL
      AND (
          (
              SELECTED_LOCATION_LEVEL = 'COUNTRY'
              AND NULLIF(TRIM(PROVINCE_STATE), '') IS NULL
              AND NULLIF(TRIM(COUNTY), '') IS NULL
          )
          OR (
              SELECTED_LOCATION_LEVEL = 'PROVINCE'
              AND NULLIF(TRIM(PROVINCE_STATE), '') IS NOT NULL
              AND NULLIF(TRIM(COUNTY), '') IS NULL
          )
          OR (
              SELECTED_LOCATION_LEVEL = 'COUNTY'
              AND NULLIF(TRIM(COUNTY), '') IS NOT NULL
          )
      )
),
AGGREGATED AS (
    SELECT
        SOURCE_COUNTRY_NAME,
        SOURCE_ISO2,
        CANONICAL_ISO2,
        CANONICAL_ISO3,
        COUNTRY_NAME,
        REPORT_DATE,
        SELECTED_LOCATION_LEVEL,
        MAPPING_STATUS,
        CASE_TYPE,
        SUM(CASES)::NUMBER(38, 0) AS SOURCE_CUMULATIVE_VALUE,
        COUNT(*) AS SOURCE_ROW_COUNT,
        COUNT(CASES) AS NON_NULL_SOURCE_ROWS,
        COUNT_IF(CASES != TRUNC(CASES)) AS FRACTIONAL_SOURCE_ROWS
    FROM SELECTED_GEOGRAPHY
    GROUP BY
        SOURCE_COUNTRY_NAME,
        SOURCE_ISO2,
        CANONICAL_ISO2,
        CANONICAL_ISO3,
        COUNTRY_NAME,
        REPORT_DATE,
        SELECTED_LOCATION_LEVEL,
        MAPPING_STATUS,
        CASE_TYPE
),
PIVOTED AS (
    SELECT
        SOURCE_COUNTRY_NAME,
        SOURCE_ISO2,
        CANONICAL_ISO2,
        CANONICAL_ISO3,
        COUNTRY_NAME,
        REPORT_DATE,
        SELECTED_LOCATION_LEVEL,
        MAPPING_STATUS,
        MAX(IFF(CASE_TYPE = 'confirmed', SOURCE_CUMULATIVE_VALUE, NULL))
            AS SOURCE_CUMULATIVE_CASES,
        MAX(IFF(CASE_TYPE = 'deaths', SOURCE_CUMULATIVE_VALUE, NULL))
            AS SOURCE_CUMULATIVE_DEATHS,
        MAX(IFF(CASE_TYPE = 'confirmed', SOURCE_ROW_COUNT, NULL))
            AS CASES_SOURCE_ROW_COUNT,
        MAX(IFF(CASE_TYPE = 'confirmed', NON_NULL_SOURCE_ROWS, NULL))
            AS CASES_NON_NULL_SOURCE_ROWS,
        MAX(IFF(CASE_TYPE = 'deaths', SOURCE_ROW_COUNT, NULL))
            AS DEATHS_SOURCE_ROW_COUNT,
        MAX(IFF(CASE_TYPE = 'deaths', NON_NULL_SOURCE_ROWS, NULL))
            AS DEATHS_NON_NULL_SOURCE_ROWS,
        MAX(IFF(CASE_TYPE = 'confirmed', FRACTIONAL_SOURCE_ROWS, NULL))
            AS FRACTIONAL_CASE_SOURCE_ROWS,
        MAX(IFF(CASE_TYPE = 'deaths', FRACTIONAL_SOURCE_ROWS, NULL))
            AS FRACTIONAL_DEATH_SOURCE_ROWS
    FROM AGGREGATED
    GROUP BY
        SOURCE_COUNTRY_NAME,
        SOURCE_ISO2,
        CANONICAL_ISO2,
        CANONICAL_ISO3,
        COUNTRY_NAME,
        REPORT_DATE,
        SELECTED_LOCATION_LEVEL,
        MAPPING_STATUS
)
SELECT *
FROM PIVOTED
WHERE SOURCE_CUMULATIVE_CASES IS NOT NULL
  AND SOURCE_CUMULATIVE_DEATHS IS NOT NULL;

CREATE OR REPLACE TRANSIENT TABLE
    COVID_ANALYTICS.STAGING.JHU_COUNTRY_DAILY
AS
WITH LAGGED AS (
    SELECT
        cumulative.*,
        LAG(SOURCE_CUMULATIVE_CASES) OVER (
            PARTITION BY CANONICAL_ISO3 ORDER BY REPORT_DATE
        ) AS PREVIOUS_CUMULATIVE_CASES,
        LAG(SOURCE_CUMULATIVE_DEATHS) OVER (
            PARTITION BY CANONICAL_ISO3 ORDER BY REPORT_DATE
        ) AS PREVIOUS_CUMULATIVE_DEATHS,
        LAG(REPORT_DATE) OVER (
            PARTITION BY CANONICAL_ISO3 ORDER BY REPORT_DATE
        ) AS PREVIOUS_REPORT_DATE
    FROM COVID_ANALYTICS.STAGING.JHU_COUNTRY_CUMULATIVE AS cumulative
)
SELECT
    SOURCE_COUNTRY_NAME,
    SOURCE_ISO2,
    CANONICAL_ISO2 AS ISO2,
    CANONICAL_ISO3 AS ISO3,
    COUNTRY_NAME,
    REPORT_DATE,
    IFF(
        PREVIOUS_CUMULATIVE_CASES IS NULL,
        SOURCE_CUMULATIVE_CASES,
        SOURCE_CUMULATIVE_CASES - PREVIOUS_CUMULATIVE_CASES
    ) AS DAILY_CASES,
    IFF(
        PREVIOUS_CUMULATIVE_DEATHS IS NULL,
        SOURCE_CUMULATIVE_DEATHS,
        SOURCE_CUMULATIVE_DEATHS - PREVIOUS_CUMULATIVE_DEATHS
    ) AS DAILY_DEATHS,
    SOURCE_CUMULATIVE_CASES,
    SOURCE_CUMULATIVE_DEATHS,
    IFF(
        PREVIOUS_CUMULATIVE_CASES IS NULL,
        SOURCE_CUMULATIVE_CASES,
        SOURCE_CUMULATIVE_CASES - PREVIOUS_CUMULATIVE_CASES
    ) < 0 AS HAS_NEGATIVE_CASE_CORRECTION,
    IFF(
        PREVIOUS_CUMULATIVE_DEATHS IS NULL,
        SOURCE_CUMULATIVE_DEATHS,
        SOURCE_CUMULATIVE_DEATHS - PREVIOUS_CUMULATIVE_DEATHS
    ) < 0 AS HAS_NEGATIVE_DEATH_CORRECTION,
    PREVIOUS_REPORT_DATE IS NULL AS IS_FIRST_OBSERVATION,
    PREVIOUS_REPORT_DATE IS NOT NULL
        AND DATEDIFF('DAY', PREVIOUS_REPORT_DATE, REPORT_DATE) != 1
        AS HAS_DATE_GAP,
    SELECTED_LOCATION_LEVEL,
    CASES_SOURCE_ROW_COUNT,
    CASES_NON_NULL_SOURCE_ROWS,
    DEATHS_SOURCE_ROW_COUNT,
    DEATHS_NON_NULL_SOURCE_ROWS,
    MAPPING_STATUS,
    'JHU'::VARCHAR(3) AS SOURCE_NAME
FROM LAGGED;

CREATE OR REPLACE VIEW
    COVID_ANALYTICS.STAGING.COVID_COUNTRY_DAILY_EXTENDED
AS
WITH ECDC_IDENTIFIED AS (
    SELECT
        ecdc.*,
        COALESCE(ecdc.COUNTRY_ISO3, code_map.COUNTRY_ISO3)
            AS CANONICAL_ISO3
    FROM COVID_ANALYTICS.STAGING.COVID_COUNTRY_DAILY AS ecdc
    LEFT JOIN COVID_ANALYTICS.STAGING.CANONICAL_COUNTRY_CODE_MAP AS code_map
        ON ecdc.COUNTRY_ISO2 = code_map.COUNTRY_ISO2
),
ECDC_IDENTITIES AS (
    SELECT
        CANONICAL_ISO3,
        LOCATION_KEY,
        COUNTRY,
        COUNTRY_ISO2,
        CANONICAL_ISO3 AS COUNTRY_ISO3,
        MAPPING_APPLIED,
        EXPECTED_POPULATION_MATCH
    FROM ECDC_IDENTIFIED
    WHERE CANONICAL_ISO3 IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CANONICAL_ISO3
        ORDER BY REPORT_DATE DESC, COUNTRY
    ) = 1
),
JHU_FIRST_DATES AS (
    SELECT ISO3, MIN(REPORT_DATE) AS FIRST_JHU_DATE
    FROM COVID_ANALYTICS.STAGING.JHU_COUNTRY_DAILY
    GROUP BY ISO3
),
BOUNDARIES AS (
    SELECT
        jhu.ISO3,
        ecdc.LOCATION_KEY IS NOT NULL AS HAS_ECDC_HISTORY,
        CASE
            WHEN ecdc.LOCATION_KEY IS NULL THEN jhu.FIRST_JHU_DATE
            ELSE COALESCE(policy.JHU_START_DATE, DATE '2020-12-15')
        END AS JHU_START_DATE
    FROM JHU_FIRST_DATES AS jhu
    LEFT JOIN ECDC_IDENTITIES AS ecdc ON jhu.ISO3 = ecdc.CANONICAL_ISO3
    LEFT JOIN COVID_ANALYTICS.RAW.JHU_GEOGRAPHY_POLICY AS policy
        ON jhu.ISO3 = policy.CANONICAL_ISO3
       AND policy.IS_INCLUDED
),
ECDC_BASELINES AS (
    SELECT
        ecdc.CANONICAL_ISO3,
        ecdc.CASES_CUMULATIVE,
        ecdc.DEATHS_CUMULATIVE
    FROM ECDC_IDENTIFIED AS ecdc
    INNER JOIN BOUNDARIES AS boundary
        ON ecdc.CANONICAL_ISO3 = boundary.ISO3
    WHERE ecdc.REPORT_DATE < boundary.JHU_START_DATE
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY ecdc.CANONICAL_ISO3
        ORDER BY ecdc.REPORT_DATE DESC
    ) = 1
),
ECDC_ACCEPTED AS (
    SELECT
        ecdc.COUNTRY,
        ecdc.COUNTRY_ISO2,
        ecdc.CANONICAL_ISO3 AS COUNTRY_ISO3,
        ecdc.LOCATION_KEY,
        ecdc.REPORT_DATE,
        ecdc.NEW_CASES_RAW,
        ecdc.NEW_DEATHS_RAW,
        ecdc.CASES_CUMULATIVE,
        ecdc.DEATHS_CUMULATIVE,
        ecdc.HAS_NEGATIVE_CASE_CORRECTION,
        ecdc.HAS_NEGATIVE_DEATH_CORRECTION,
        ecdc.SOURCE_ROW_COUNT,
        ecdc.MAPPING_APPLIED,
        ecdc.EXPECTED_POPULATION_MATCH,
        'ECDC'::VARCHAR(4) AS SOURCE_NAME,
        'ECDC_BASELINE'::VARCHAR AS SERIES_SEGMENT,
        boundary.JHU_START_DATE,
        'COUNTRY'::VARCHAR AS SELECTED_LOCATION_LEVEL,
        CASE
            WHEN ecdc.MAPPING_APPLIED THEN 'EXPLICIT_MAPPING'
            WHEN ecdc.CANONICAL_ISO3 IS NOT NULL THEN 'MAPPED'
            ELSE 'UNMAPPED'
        END AS MAPPING_STATUS,
        ecdc.CASES_CUMULATIVE AS SOURCE_CUMULATIVE_CASES,
        ecdc.DEATHS_CUMULATIVE AS SOURCE_CUMULATIVE_DEATHS
    FROM ECDC_IDENTIFIED AS ecdc
    LEFT JOIN BOUNDARIES AS boundary
        ON ecdc.CANONICAL_ISO3 = boundary.ISO3
    WHERE boundary.ISO3 IS NULL
       OR ecdc.REPORT_DATE < boundary.JHU_START_DATE
),
JHU_ACCEPTED_BASE AS (
    SELECT
        COALESCE(ecdc.COUNTRY, jhu.COUNTRY_NAME) AS COUNTRY,
        COALESCE(ecdc.COUNTRY_ISO2, jhu.ISO2) AS COUNTRY_ISO2,
        jhu.ISO3 AS COUNTRY_ISO3,
        COALESCE(ecdc.LOCATION_KEY, jhu.ISO3) AS LOCATION_KEY,
        jhu.REPORT_DATE,
        jhu.DAILY_CASES AS NEW_CASES_RAW,
        jhu.DAILY_DEATHS AS NEW_DEATHS_RAW,
        boundary.HAS_ECDC_HISTORY,
        baseline.CASES_CUMULATIVE AS ECDC_BASELINE_CASES,
        baseline.DEATHS_CUMULATIVE AS ECDC_BASELINE_DEATHS,
        jhu.SOURCE_CUMULATIVE_CASES,
        jhu.SOURCE_CUMULATIVE_DEATHS,
        jhu.HAS_NEGATIVE_CASE_CORRECTION,
        jhu.HAS_NEGATIVE_DEATH_CORRECTION,
        GREATEST(
            jhu.CASES_SOURCE_ROW_COUNT,
            jhu.DEATHS_SOURCE_ROW_COUNT
        ) AS SOURCE_ROW_COUNT,
        jhu.MAPPING_STATUS != 'MAPPED' AS MAPPING_APPLIED,
        population.COUNTRY_CODE_ISO3 IS NOT NULL AS EXPECTED_POPULATION_MATCH,
        boundary.JHU_START_DATE,
        jhu.SELECTED_LOCATION_LEVEL,
        jhu.MAPPING_STATUS
    FROM COVID_ANALYTICS.STAGING.JHU_COUNTRY_DAILY AS jhu
    INNER JOIN BOUNDARIES AS boundary ON jhu.ISO3 = boundary.ISO3
    LEFT JOIN ECDC_IDENTITIES AS ecdc ON jhu.ISO3 = ecdc.CANONICAL_ISO3
    LEFT JOIN ECDC_BASELINES AS baseline
        ON jhu.ISO3 = baseline.CANONICAL_ISO3
    LEFT JOIN COVID_ANALYTICS.RAW.WORLD_BANK_POPULATION_2020 AS population
        ON jhu.ISO3 = population.COUNTRY_CODE_ISO3
    WHERE jhu.REPORT_DATE >= boundary.JHU_START_DATE
),
JHU_ACCEPTED AS (
    SELECT
        COUNTRY,
        COUNTRY_ISO2,
        COUNTRY_ISO3,
        LOCATION_KEY,
        REPORT_DATE,
        NEW_CASES_RAW,
        NEW_DEATHS_RAW,
        IFF(
            HAS_ECDC_HISTORY,
            ECDC_BASELINE_CASES + SUM(NEW_CASES_RAW) OVER (
                PARTITION BY COUNTRY_ISO3
                ORDER BY REPORT_DATE
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
            ),
            SOURCE_CUMULATIVE_CASES
        ) AS CASES_CUMULATIVE,
        IFF(
            HAS_ECDC_HISTORY,
            ECDC_BASELINE_DEATHS + SUM(NEW_DEATHS_RAW) OVER (
                PARTITION BY COUNTRY_ISO3
                ORDER BY REPORT_DATE
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
            ),
            SOURCE_CUMULATIVE_DEATHS
        ) AS DEATHS_CUMULATIVE,
        HAS_NEGATIVE_CASE_CORRECTION,
        HAS_NEGATIVE_DEATH_CORRECTION,
        SOURCE_ROW_COUNT,
        MAPPING_APPLIED,
        EXPECTED_POPULATION_MATCH,
        'JHU'::VARCHAR(4) AS SOURCE_NAME,
        IFF(
            HAS_ECDC_HISTORY,
            'JHU_CONTINUATION',
            'JHU_ONLY'
        )::VARCHAR AS SERIES_SEGMENT,
        JHU_START_DATE,
        SELECTED_LOCATION_LEVEL,
        MAPPING_STATUS,
        SOURCE_CUMULATIVE_CASES,
        SOURCE_CUMULATIVE_DEATHS
    FROM JHU_ACCEPTED_BASE
)
SELECT * FROM ECDC_ACCEPTED
UNION ALL
SELECT * FROM JHU_ACCEPTED;

CREATE OR REPLACE VIEW
    COVID_ANALYTICS.MARTS.CASE_INCREASE_PATTERNS_EXTENDED
AS
SELECT *
FROM COVID_ANALYTICS.STAGING.COVID_COUNTRY_DAILY_EXTENDED
MATCH_RECOGNIZE (
    PARTITION BY
        LOCATION_KEY,
        COUNTRY,
        COUNTRY_ISO2,
        COUNTRY_ISO3,
        SERIES_SEGMENT
    ORDER BY REPORT_DATE
    MEASURES
        MATCH_NUMBER() AS MATCH_NUMBER,
        FIRST(REPORT_DATE) AS START_DATE,
        LAST(REPORT_DATE) AS END_DATE,
        COUNT(*) AS DAYS_IN_PATTERN,
        COUNT(INCREASE_DAY.*) AS CONSECUTIVE_INCREASES,
        FIRST(NEW_CASES_RAW) AS START_CASES,
        LAST(NEW_CASES_RAW) AS END_CASES
    ONE ROW PER MATCH
    AFTER MATCH SKIP PAST LAST ROW
    PATTERN (START_DAY INCREASE_DAY{3,})
    DEFINE
        START_DAY AS TRUE,
        INCREASE_DAY AS NEW_CASES_RAW > LAG(NEW_CASES_RAW)
            AND DATEDIFF('DAY', LAG(REPORT_DATE), REPORT_DATE) = 1
);

CREATE OR REPLACE TRANSIENT TABLE
    COVID_ANALYTICS.MARTS.COUNTRY_COVID_DENOMINATOR_EXTENDED
AS
WITH REQUIRED_COUNTRIES AS (
    SELECT DISTINCT COUNTRY_ISO3 AS ISO3
    FROM COVID_ANALYTICS.STAGING.COVID_COUNTRY_DAILY_EXTENDED
    WHERE COUNTRY_ISO3 IS NOT NULL
),
CANDIDATES AS (
    SELECT
        legacy.COUNTRY_CODE_ISO2 AS ISO2,
        legacy.COUNTRY_CODE_ISO3 AS ISO3,
        legacy.COUNTRY_NAME,
        legacy.POPULATION AS COVID_RATE_POPULATION_2020,
        legacy.POPULATION_YEAR,
        'legacy-world-bank-population-2020'::VARCHAR AS SOURCE_SNAPSHOT_ID,
        'v1-extended-candidate'::VARCHAR AS DENOMINATOR_VERSION,
        'legacy_2020_population_parallel_candidate'::VARCHAR
            AS DENOMINATOR_POLICY,
        TRUE AS IS_FROZEN,
        NULL::TIMESTAMP_TZ AS APPROVED_AT,
        'CANDIDATE'::VARCHAR AS DENOMINATOR_PUBLICATION_STATUS
    FROM REQUIRED_COUNTRIES AS required
    INNER JOIN COVID_ANALYTICS.RAW.WORLD_BANK_POPULATION_2020 AS legacy
        ON required.ISO3 = legacy.COUNTRY_CODE_ISO3
    WHERE NOT EXISTS (
        SELECT 1
        FROM COVID_ANALYTICS.MARTS.COUNTRY_COVID_DENOMINATOR AS approved
        WHERE approved.ISO3 = required.ISO3
    )
)
SELECT
    approved.*,
    'ACTIVE'::VARCHAR AS DENOMINATOR_PUBLICATION_STATUS
FROM COVID_ANALYTICS.MARTS.COUNTRY_COVID_DENOMINATOR AS approved
UNION ALL
SELECT * FROM CANDIDATES;

CREATE OR REPLACE VIEW
    COVID_ANALYTICS.MARTS.COVID_ENRICHED_EXTENDED
AS
SELECT
    covid.COUNTRY,
    COALESCE(covid.COUNTRY_ISO2, denominator.ISO2) AS COUNTRY_ISO2,
    COALESCE(covid.COUNTRY_ISO3, denominator.ISO3) AS COUNTRY_ISO3,
    covid.LOCATION_KEY,
    covid.REPORT_DATE,
    covid.NEW_CASES_RAW,
    covid.NEW_DEATHS_RAW,
    covid.CASES_CUMULATIVE,
    covid.DEATHS_CUMULATIVE,
    denominator.COUNTRY_NAME AS DENOMINATOR_COUNTRY_NAME,
    denominator.COVID_RATE_POPULATION_2020,
    denominator.POPULATION_YEAR AS COVID_RATE_POPULATION_YEAR,
    denominator.SOURCE_SNAPSHOT_ID AS DENOMINATOR_SOURCE_SNAPSHOT_ID,
    denominator.DENOMINATOR_VERSION,
    denominator.DENOMINATOR_POLICY,
    denominator.IS_FROZEN AS DENOMINATOR_IS_FROZEN,
    denominator.DENOMINATOR_PUBLICATION_STATUS,
    ROUND(
        covid.NEW_CASES_RAW
        / NULLIF(denominator.COVID_RATE_POPULATION_2020, 0) * 100000,
        2
    ) AS NEW_CASES_PER_100K,
    ROUND(
        covid.NEW_DEATHS_RAW
        / NULLIF(denominator.COVID_RATE_POPULATION_2020, 0) * 100000,
        2
    ) AS NEW_DEATHS_PER_100K,
    ROUND(
        covid.CASES_CUMULATIVE
        / NULLIF(denominator.COVID_RATE_POPULATION_2020, 0) * 100000,
        2
    ) AS CASES_PER_100K,
    ROUND(
        covid.DEATHS_CUMULATIVE
        / NULLIF(denominator.COVID_RATE_POPULATION_2020, 0) * 100000,
        2
    ) AS DEATHS_PER_100K,
    ROUND(
        covid.DEATHS_CUMULATIVE
        / NULLIF(covid.CASES_CUMULATIVE, 0) * 100,
        4
    ) AS MORTALITY_RATE_PERCENT,
    CASE
        WHEN denominator.DENOMINATOR_PUBLICATION_STATUS = 'CANDIDATE'
            THEN 'MATCHED_CANDIDATE'
        WHEN denominator.COVID_RATE_POPULATION_2020 IS NOT NULL THEN 'MATCHED'
        WHEN NOT covid.EXPECTED_POPULATION_MATCH THEN 'SOURCE_UNAVAILABLE'
        WHEN covid.COUNTRY_ISO2 IS NULL AND covid.COUNTRY_ISO3 IS NULL
            THEN 'NO_ISO_CODE'
        ELSE 'UNMATCHED'
    END AS DENOMINATOR_JOIN_STATUS,
    covid.HAS_NEGATIVE_CASE_CORRECTION,
    covid.HAS_NEGATIVE_DEATH_CORRECTION,
    covid.MAPPING_APPLIED,
    covid.SOURCE_ROW_COUNT,
    covid.SOURCE_NAME,
    covid.SERIES_SEGMENT,
    covid.JHU_START_DATE,
    covid.SELECTED_LOCATION_LEVEL,
    covid.MAPPING_STATUS,
    covid.SOURCE_CUMULATIVE_CASES,
    covid.SOURCE_CUMULATIVE_DEATHS
FROM COVID_ANALYTICS.STAGING.COVID_COUNTRY_DAILY_EXTENDED AS covid
LEFT JOIN COVID_ANALYTICS.MARTS.COUNTRY_COVID_DENOMINATOR_EXTENDED AS denominator
    ON covid.COUNTRY_ISO3 = denominator.ISO3
    OR (
        covid.COUNTRY_ISO3 IS NULL
        AND covid.COUNTRY_ISO2 = denominator.ISO2
    );

