CREATE OR REPLACE TRANSIENT TABLE
    COVID_ANALYTICS.APP.ECDC_JHU_OVERLAP_AUDIT
AS
WITH ECDC_IDENTIFIED AS (
    SELECT
        COALESCE(ecdc.COUNTRY_ISO3, code_map.COUNTRY_ISO3) AS ISO3,
        COALESCE(ecdc.COUNTRY_ISO2, code_map.COUNTRY_ISO2) AS ISO2,
        ecdc.COUNTRY AS COUNTRY_NAME,
        ecdc.REPORT_DATE,
        ecdc.NEW_CASES_RAW AS ECDC_DAILY_CASES,
        ecdc.NEW_DEATHS_RAW AS ECDC_DAILY_DEATHS,
        ecdc.CASES_CUMULATIVE AS ECDC_CUMULATIVE_CASES,
        ecdc.DEATHS_CUMULATIVE AS ECDC_CUMULATIVE_DEATHS
    FROM COVID_ANALYTICS.STAGING.COVID_COUNTRY_DAILY AS ecdc
    LEFT JOIN COVID_ANALYTICS.STAGING.CANONICAL_COUNTRY_CODE_MAP AS code_map
        ON ecdc.COUNTRY_ISO2 = code_map.COUNTRY_ISO2
    WHERE COALESCE(ecdc.COUNTRY_ISO3, code_map.COUNTRY_ISO3) IS NOT NULL
),
OVERLAP_BOUNDS AS (
    SELECT
        (SELECT MIN(REPORT_DATE)
         FROM COVID_ANALYTICS.STAGING.JHU_COUNTRY_DAILY) AS FIRST_DATE,
        (SELECT MAX(REPORT_DATE)
         FROM ECDC_IDENTIFIED) AS LAST_DATE
),
ECDC_OVERLAP AS (
    SELECT ecdc.*
    FROM ECDC_IDENTIFIED AS ecdc
    CROSS JOIN OVERLAP_BOUNDS AS bounds
    WHERE ecdc.REPORT_DATE BETWEEN bounds.FIRST_DATE AND bounds.LAST_DATE
),
JHU_OVERLAP AS (
    SELECT jhu.*
    FROM COVID_ANALYTICS.STAGING.JHU_COUNTRY_DAILY AS jhu
    CROSS JOIN OVERLAP_BOUNDS AS bounds
    WHERE jhu.REPORT_DATE BETWEEN bounds.FIRST_DATE AND bounds.LAST_DATE
)
SELECT
    COALESCE(ecdc.ISO2, jhu.ISO2) AS ISO2,
    COALESCE(ecdc.ISO3, jhu.ISO3) AS ISO3,
    COALESCE(ecdc.COUNTRY_NAME, jhu.COUNTRY_NAME) AS COUNTRY_NAME,
    COALESCE(ecdc.REPORT_DATE, jhu.REPORT_DATE) AS REPORT_DATE,
    CASE
        WHEN ecdc.ISO3 IS NOT NULL AND jhu.ISO3 IS NOT NULL THEN 'BOTH'
        WHEN ecdc.ISO3 IS NOT NULL THEN 'ECDC_ONLY'
        ELSE 'JHU_ONLY'
    END AS MATCH_STATUS,
    ecdc.ECDC_DAILY_CASES,
    jhu.DAILY_CASES AS JHU_DAILY_CASES,
    ecdc.ECDC_DAILY_DEATHS,
    jhu.DAILY_DEATHS AS JHU_DAILY_DEATHS,
    ecdc.ECDC_CUMULATIVE_CASES,
    jhu.SOURCE_CUMULATIVE_CASES AS JHU_CUMULATIVE_CASES,
    ecdc.ECDC_CUMULATIVE_DEATHS,
    jhu.SOURCE_CUMULATIVE_DEATHS AS JHU_CUMULATIVE_DEATHS,
    ecdc.ECDC_DAILY_CASES - jhu.DAILY_CASES AS DAILY_CASE_DIFFERENCE,
    ABS(ecdc.ECDC_DAILY_CASES - jhu.DAILY_CASES)
        AS ABS_DAILY_CASE_DIFFERENCE,
    ecdc.ECDC_DAILY_DEATHS - jhu.DAILY_DEATHS AS DAILY_DEATH_DIFFERENCE,
    ABS(ecdc.ECDC_DAILY_DEATHS - jhu.DAILY_DEATHS)
        AS ABS_DAILY_DEATH_DIFFERENCE,
    ecdc.ECDC_CUMULATIVE_CASES - jhu.SOURCE_CUMULATIVE_CASES
        AS CUMULATIVE_CASE_DIFFERENCE,
    ecdc.ECDC_CUMULATIVE_DEATHS - jhu.SOURCE_CUMULATIVE_DEATHS
        AS CUMULATIVE_DEATH_DIFFERENCE
FROM ECDC_OVERLAP AS ecdc
FULL OUTER JOIN JHU_OVERLAP AS jhu
    ON ecdc.ISO3 = jhu.ISO3
   AND ecdc.REPORT_DATE = jhu.REPORT_DATE;

-- Compact release evidence. Bootstrap applies the corresponding postconditions.
SELECT
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT ISO3) AS COUNTRY_COUNT,
    MIN(REPORT_DATE) AS FIRST_DATE,
    MAX(REPORT_DATE) AS LAST_DATE,
    COUNT_IF(ISO3 IS NULL) AS NULL_ISO3_ROWS,
    COUNT_IF(HAS_DATE_GAP) AS DATE_GAP_ROWS,
    COUNT_IF(HAS_NEGATIVE_CASE_CORRECTION) AS NEGATIVE_CASE_CORRECTIONS,
    COUNT_IF(HAS_NEGATIVE_DEATH_CORRECTION) AS NEGATIVE_DEATH_CORRECTIONS
FROM COVID_ANALYTICS.STAGING.JHU_COUNTRY_DAILY;

SELECT
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT LOCATION_KEY) AS LOCATION_COUNT,
    COUNT_IF(SERIES_SEGMENT = 'ECDC_BASELINE') AS ECDC_ROWS,
    COUNT_IF(SERIES_SEGMENT = 'JHU_ONLY') AS JHU_ONLY_ROWS,
    MIN(REPORT_DATE) AS FIRST_DATE,
    MAX(REPORT_DATE) AS LAST_DATE
FROM COVID_ANALYTICS.STAGING.COVID_COUNTRY_DAILY_EXTENDED;

SELECT
    COUNT(*) AS PATTERN_COUNT,
    COUNT(DISTINCT LOCATION_KEY) AS LOCATION_COUNT,
    MIN(START_DATE) AS FIRST_PATTERN_DATE,
    MAX(END_DATE) AS LAST_PATTERN_DATE,
    COUNT_IF(DAYS_IN_PATTERN != CONSECUTIVE_INCREASES + 1)
        AS INVALID_DURATION_ROWS,
    COUNT_IF(CONSECUTIVE_INCREASES < 3) AS INVALID_INCREASE_ROWS
FROM COVID_ANALYTICS.MARTS.CASE_INCREASE_PATTERNS_EXTENDED;

SELECT
    MATCH_STATUS,
    COUNT(*) AS ROW_COUNT,
    COUNT(DISTINCT ISO3) AS COUNTRY_COUNT
FROM COVID_ANALYTICS.APP.ECDC_JHU_OVERLAP_AUDIT
GROUP BY MATCH_STATUS
ORDER BY MATCH_STATUS;
