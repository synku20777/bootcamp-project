-- Build the version-selected WDI context independently of the frozen denominator.
-- The publisher creates and activates the permanent RAW tables before this file runs.

USE ROLE COVID_PROJECT_ADMIN;
USE WAREHOUSE COVID_WH;

CREATE OR REPLACE TRANSIENT TABLE COVID_ANALYTICS.MARTS.DIM_COUNTRY AS
SELECT
    covid.LOCATION_KEY,
    covid.COUNTRY,
    COALESCE(covid.COUNTRY_ISO2, legacy.COUNTRY_CODE_ISO2) AS ISO2,
    COALESCE(covid.COUNTRY_ISO3, legacy.COUNTRY_CODE_ISO3) AS ISO3,
    COALESCE(covid.COUNTRY_ISO3, legacy.COUNTRY_CODE_ISO3) IS NOT NULL
        AS IS_WORLD_BANK_CONTEXT_ELIGIBLE
FROM COVID_ANALYTICS.STAGING.COVID_COUNTRY_DAILY AS covid
LEFT JOIN COVID_ANALYTICS.RAW.WORLD_BANK_POPULATION_2020 AS legacy
    ON covid.COUNTRY_ISO2 = legacy.COUNTRY_CODE_ISO2
    OR covid.COUNTRY_ISO3 = legacy.COUNTRY_CODE_ISO3
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY covid.LOCATION_KEY
    ORDER BY covid.REPORT_DATE DESC, covid.COUNTRY
) = 1;

CREATE OR REPLACE VIEW
    COVID_ANALYTICS.STAGING.WORLD_BANK_COUNTRY_INDICATORS_CURRENT
AS
SELECT indicators.*
FROM COVID_ANALYTICS.RAW.WORLD_BANK_COUNTRY_INDICATORS AS indicators
INNER JOIN COVID_ANALYTICS.RAW.WORLD_BANK_INDICATOR_SNAPSHOTS AS snapshots
    ON indicators.SNAPSHOT_ID = snapshots.SNAPSHOT_ID
WHERE snapshots.IS_ACTIVE = TRUE
  AND snapshots.PUBLICATION_STATUS = 'ACTIVE';

CREATE OR REPLACE VIEW
    COVID_ANALYTICS.STAGING.WORLD_BANK_COUNTRY_INDICATORS_CLEAN
AS
SELECT
    SNAPSHOT_ID,
    CANONICAL_ISO2 AS ISO2,
    CANONICAL_ISO3 AS ISO3,
    COUNTRY_NAME,
    INDICATOR_CODE,
    INDICATOR_NAME,
    INDICATOR_UNIT,
    OBSERVATION_YEAR,
    INDICATOR_VALUE,
    IFF(INDICATOR_VALUE IS NULL, 'missing', 'available') AS VALUE_STATUS,
    SOURCE_LAST_UPDATED
FROM COVID_ANALYTICS.STAGING.WORLD_BANK_COUNTRY_INDICATORS_CURRENT
WHERE IDENTITY_MAPPING_STATUS IN ('matched_iso', 'matched_explicit_mapping')
  AND NOT IS_AGGREGATE
  AND OBSERVATION_YEAR BETWEEN 2019 AND 2021
  AND INDICATOR_CODE IN (
      'SP.POP.TOTL',
      'EN.POP.DNST',
      'SP.POP.65UP.TO.ZS',
      'NY.GDP.PCAP.KD',
      'SH.XPD.CHEX.PP.CD'
  )
  AND (
      (INDICATOR_CODE = 'SP.POP.TOTL'
       AND INDICATOR_NAME = 'Population, total'
       AND INDICATOR_UNIT = 'people')
      OR (INDICATOR_CODE = 'EN.POP.DNST'
          AND INDICATOR_NAME = 'Population density (people per sq. km of land area)'
          AND INDICATOR_UNIT = 'people per sq. km of land area')
      OR (INDICATOR_CODE = 'SP.POP.65UP.TO.ZS'
          AND INDICATOR_NAME = 'Population ages 65 and above (% of total population)'
          AND INDICATOR_UNIT = '% of total population')
      OR (INDICATOR_CODE = 'NY.GDP.PCAP.KD'
          AND INDICATOR_NAME = 'GDP per capita (constant 2015 US$)'
          AND INDICATOR_UNIT = 'constant 2015 US$')
      OR (INDICATOR_CODE = 'SH.XPD.CHEX.PP.CD'
          AND INDICATOR_NAME = 'Current health expenditure per capita, PPP (current international $)'
          AND INDICATOR_UNIT = 'current international $')
  );

